import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const content=JSON.parse(fs.readFileSync('data/journey-data.json','utf8'));
const store=new Map();
const context={structuredClone,window:{JOURNEY_DATA:content},localStorage:{getItem:k=>store.get(k),setItem:(k,v)=>store.set(k,v)}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('companion.js','utf8'),context);
const make=()=>context.window.createGuideCompanion({esc:String,storageKey:k=>'test-'+k,touchSave:()=>{},navigate:()=>{},data:{pokemon:[]},openPokemon:()=>{}});
const guide=make();
guide.restore({completed:['#1','#1','missing'],strata:2,notes:'A field note'});
const snapshot=JSON.parse(JSON.stringify(guide.serialize()));
assert.deepEqual(snapshot.completed,['#1']);
assert.equal(snapshot.strata,2);
assert.deepEqual(JSON.parse(JSON.stringify(make().serialize())),snapshot,'Journey survives reopening');
guide.restore({completed:[],strata:999,notes:'x'.repeat(21000)});
assert.equal(guide.serialize().strata,8);
assert.equal(guide.serialize().notes.length,20000);
guide.restore(undefined);
assert.equal(guide.serialize().completed.length,0,'Older saves initialize empty journey');
store.set('test-journey-v1','broken JSON');
assert.equal(make().serialize().strata,0,'Corrupt local journey recovers safely');
const core=JSON.parse(fs.readFileSync('data/guide-data.json','utf8'));
assert.equal(core.pokemon.length,409);
assert.deepEqual([...core.pokemon.map(p=>p.gameDexId)].sort((a,b)=>a-b),Array.from({length:409},(_,i)=>i+1));
const bosses=JSON.parse(fs.readFileSync('data/battle-data.json','utf8')).battles;
assert.equal(bosses.filter(b=>b.mode==='Hard').length,37);
assert.equal(bosses.filter(b=>b.mode==='Mode unspecified').length,8);
assert.equal(bosses.filter(b=>['Normal','Picnic'].includes(b.mode)).length,0);
assert.equal(content.quests.length,38);
assert.equal(content.quests[0].reward,'Poké Ball x5');
assert.ok(content.quests.every(q=>q.name&&q.description&&q.location&&q.source));
const app=fs.readFileSync('app.js','utf8');
assert.ok(app.includes('journey:companion.serialize()')&&app.includes('companion.restore(save.journey)'));
assert.ok(app.includes('backupLocal(source==='),'Import preserves recovery snapshot');
console.log('Passed journey persistence/recovery, exact Dex membership, difficulty separation, quest and save integration checks.');
